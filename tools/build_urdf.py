"""Generate the CR5 URDF from the Dobot xacro with the Robotiq 2F-85 gripper.

Output:
    urdf/cr5_robot.urdf: Robotiq 2F-85 gripper (pick & place simulation app)

Changes to Dobot's xacro:
- Gazebo tags removed, mesh paths made relative to urdf/.
- Joint velocity limits set to 3.14 rad/s (CR5 spec: 180 deg/s; original xacro says 100).
- `gripper` link: the Robotiq 2F-85 in its open state as one mesh (meshes/obj/robotiq_2f85_open.obj),
  exported from the MuJoCo Menagerie model, so PyRoKi and cuRobo see its geometry.
- `tcp` link: the fingertip pinch point, used as the IK and motion planning target.

Run:
    python tools/build_urdf.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import mujoco
import numpy as onp
import trimesh
from scipy.spatial.transform import Rotation

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from cr5sim import paths  # noqa: E402

GRIPPER_LINKS = """
  <!-- Robotiq 2F-85 (open), mounted directly on the flange: the flange face is the
       Link6 origin with +z pointing out. -->
  <link name="gripper">
    <inertial>
      <origin xyz="0 0 {com_z:.4f}" rpy="0 0 0" />
      <mass value="{mass:.4f}" />
      <inertia ixx="0.0006" ixy="0" ixz="0" iyy="0.0006" iyz="0" izz="0.0004" />
    </inertial>
    <visual>
      <geometry><mesh filename="../meshes/obj/robotiq_2f85_open.obj" /></geometry>
    </visual>
    <collision>
      <geometry><mesh filename="../meshes/obj/robotiq_2f85_open.obj" /></geometry>
    </collision>
  </link>
  <joint name="gripper_mount" type="fixed">
    <origin xyz="0 0 0" rpy="0 0 0" />
    <parent link="Link6" />
    <child link="gripper" />
  </joint>

  <link name="tcp" />
  <joint name="tcp_joint" type="fixed">
    <origin xyz="0 0 {tcp_z:.4f}" rpy="{tcp_rpy}" />
    <parent link="gripper" />
    <child link="tcp" />
  </joint>
"""


def export_gripper_mesh() -> tuple[float, str, float, float]:
    """Merge the open 2F-85's visual meshes into one OBJ.

    Returns (tcp_z, tcp_rpy, mass, com_z), with the TCP frame equal to MuJoCo's pinch site.
    """
    model = mujoco.MjModel.from_xml_path(str(paths.GRIPPER_MJCF))
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)  # qpos = 0 is fully open
    parts = []
    for g in range(model.ngeom):
        if model.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH or model.geom_group[g] != 2:
            continue
        mesh_id = model.geom_dataid[g]
        v0, nv = model.mesh_vertadr[mesh_id], model.mesh_vertnum[mesh_id]
        f0, nf = model.mesh_faceadr[mesh_id], model.mesh_facenum[mesh_id]
        verts = model.mesh_vert[v0 : v0 + nv] @ data.geom_xmat[g].reshape(3, 3).T + data.geom_xpos[g]
        parts.append(trimesh.Trimesh(verts, model.mesh_face[f0 : f0 + nf], process=False))
    trimesh.util.concatenate(parts).export(paths.OBJ_DIR / "robotiq_2f85_open.obj")
    root = model.body("base_mount").id
    # URDF rpy is extrinsic XYZ.
    rpy = Rotation.from_matrix(data.site("pinch").xmat.reshape(3, 3)).as_euler("xyz")
    return (
        float(data.site("pinch").xpos[2]),
        " ".join(f"{a:.6f}" for a in rpy),
        float(model.body_subtreemass[root]),
        float(data.subtree_com[root][2]),
    )


def base_urdf() -> str:
    """The arm alone: the xacro with Gazebo tags removed, relative meshes, real speed limits."""
    src = paths.XACRO.read_text()
    src = re.sub(r"\s*<!-- Disable physics.*?</robot>", "\n\n</robot>", src, flags=re.S)
    src = src.replace(' xmlns:xacro="http://ros.org/wiki/xacro"', "")
    src = src.replace("package://dobot_description/meshes/cr5/", "../Assets/")
    src = src.replace('effort="300" velocity="100"', 'effort="300" velocity="3.14"')
    names = {"0 0 0 1": "cr5_black", "1 1 1 1": "cr5_white"}
    return re.sub(
        r'<material\s+name="">(\s*<color rgba="([^"]+)" />)',
        lambda m: f'<material name="{names.get(m.group(2), "cr5_" + m.group(2).replace(" ", "_"))}">{m.group(1)}',
        src,
    )


def write_urdf(path: Path, src: str, tool_links: str, tool_name: str) -> None:
    src = src.replace("\n</robot>", tool_links + "\n</robot>")
    header = (
        "<!-- Generated by tools/build_urdf.py from Assets/cr5_robot.xacro. Do not edit.\n"
        "     Changes: Gazebo tags removed, mesh paths relative, velocity limits 3.14 rad/s,\n"
        f"     {tool_name} links added. -->\n"
    )
    src = src.replace('<?xml version="1.0"?>\n', '<?xml version="1.0"?>\n' + header, 1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(src)


def main() -> None:
    src = base_urdf()
    paths.OBJ_DIR.mkdir(parents=True, exist_ok=True)

    tcp_z, tcp_rpy, mass, com_z = export_gripper_mesh()
    assert onp.isfinite(tcp_z)
    gripper = GRIPPER_LINKS.format(tcp_z=tcp_z, tcp_rpy=tcp_rpy, mass=mass, com_z=com_z)
    write_urdf(paths.URDF, src, gripper, "Robotiq 2F-85 + tcp")
    print(f"Wrote {paths.URDF} (tcp z = {tcp_z * 1000:.1f} mm from flange, gripper {mass:.3f} kg)")


if __name__ == "__main__":
    main()
